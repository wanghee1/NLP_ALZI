"""쿼리 변환 (HyDE 방식) — 검색 품질 개선용.

사용자의 일상어 질문("주휴수당")과 법조문 표현("유급휴일") 사이 어휘 간극 때문에
핵심 조문이 검색에 안 잡히는 문제를 완화한다. 질문을 "법조문이 쓸 법한 가상 조문 문장"
으로 변환한 뒤 그 문장으로 검색한다 (HyDE: Hypothetical Document Embeddings).

중요: 변환 결과(가상 조문)는 '검색 쿼리'로만 쓰고 사용자에게 보여주지 않는다.
      이것은 '정답'이 아니므로 답변 생성(chain)에서 근거로 쓰면 안 된다 (rag-and-llm: 할루시네이션 차단).

순수 로직 계층(src/rag)이라 전송 계층(api/)에 의존하지 않는다.
LLM 호출은 공용 클라이언트(src/llm/client)를 쓴다. 키는 거기서 config.settings 경유로
로딩하며 로그/예외에 노출하지 않는다 (security 규칙).
"""

from __future__ import annotations

from src.llm.client import complete

# 변환 일관성을 위해 온도는 낮게 둔다 (창의성보다 안정적인 법률 표현 번역이 목적).
_TEMPERATURE = 0.2
# 가상 조문은 1~3문장이면 충분하다.
_MAX_TOKENS = 300

# 가드를 프롬프트에 명시한다. 핵심은 (1) 검색용 쿼리일 뿐 정답이 아님,
# (2) 구체 수치(조문번호·금액·일수) 생성 금지, (3) 일상어→법률 표현 번역.
_SYSTEM_PROMPT = """당신은 한국 노동법 벡터 검색을 돕는 "쿼리 변환기"다.
사용자의 일상어 질문을, 관련 법조문이 실제로 쓸 법한 표현의 "가상 조문 문장"으로 변환하라.
이 문장은 검색 쿼리로만 쓰이고 사용자에게 보여주지 않는다.

규칙:
1) 이 문장은 '정답'이 아니라 '검색용 쿼리'다. 관련 법조문이 쓸 법한 표현과 키워드를 담아 1~3문장으로 작성한다.
2) 조문 번호·금액·일수·비율 등 구체적 수치는 절대 쓰지 마라.
   (예: "제55조", "30일", "9,860원", "80%" 금지) 일반적인 법률 표현만 사용한다.
3) 일상어를 법률 표현으로 번역하는 데 집중한다. 예:
   - 주휴수당 → 유급휴일, 1주 평균 1회 이상의 유급휴일 보장
   - 부당해고 → 정당한 이유 없는 해고, 해고의 제한
   - 월급 떼임/안 줌 → 임금 미지급, 금품 청산, 임금 지급 의무
4) 변환된 문장만 출력한다. 설명·머리말·따옴표 없이."""


def transform_query(user_query: str) -> str:
    """사용자 질문을 검색용 '가상 조문 문장'으로 변환해 반환한다.

    Args:
        user_query: 사용자의 일상어 질문

    Returns:
        법률 표현으로 변환된 검색용 문장. 빈 응답이면 원본 질문으로 폴백한다
        (변환 실패가 곧 검색 불능으로 이어지지 않게).

    Raises:
        RuntimeError: LLM 호출 실패 (키는 메시지에 노출하지 않음).
    """
    transformed = complete(
        system=_SYSTEM_PROMPT,
        user=user_query,
        max_tokens=_MAX_TOKENS,
        temperature=_TEMPERATURE,
    )
    return transformed or user_query
